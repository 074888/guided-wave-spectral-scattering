function [C_Cor]=TransCoor(Elastic,a1,b1,c1,a2,b2,c2,a3,b3,c3)%Input tow Coordinate system included angle

% abc1 is the angle of x1 with x'123;

% l1=0;l2=0;l3=1;
% m1=0;m2=1;m3=0;
% n1=1;n2=0;n3=0;

l1=cosd(a1);l2=cosd(b1);l3=cosd(c1);
m1=cosd(a2);m2=cosd(b2);m3=cosd(c2);
n1=cosd(a3);n2=cosd(b3);n3=cosd(c3);

Aa_In=[l1.^2 l2.^2 l3.^2 2*l2*l3 2*l3*l1 2*l1*l2;...
        m1.^2 m2.^2 m3.^2 2*m2*m3 2*m3*m1 2*m1*m2;...
        n1.^2 n2.^2 n3.^2 2*n2*n3 2*n3*n1 2*n1*n2;...
        m1*n1 m2*n2 m3*n3 m2*n3+m3*n2 m3*n1+m1*n3 m1*n2+m2*n1;...
        n1*l1 n2*l2 m3*l3 n2*l3+n3*l2 n3*l1+n1*l3 n1*l2+n2*l1;...
        l1*m1 l2*m2 l3*m3 l2*m3+l3*m2 l3*m1+l1*m3 l1*m2+l2*m1];

Bb=[l1.^2 m1.^2 n1.^2 m1*n1 n1*l1 l1*m1;...
    l2.^2 m2.^2 n2.^2 m2*n2 n2*l2 l2*m2;...
    l3.^2 m3.^2 n3.^2 m3*n3 n3*l3 l3*m3;...
    2*l2*l3 2*m2*m3 2*n2*n3 m2*n3+m3*n2 n2*l3+n3*l2 l2*m3+l3*m2;...
    2*l3*l1 2*m3*m1 2*n3*n1 m3*n1+m1*n3 n3*l1+n1*l3 l3*m1+l1*m3;...
    2*l1*l2 2*m1*m2 2*n1*n2 m1*n2+m2*n1 n1*l2+n2*l1 l1*m2+l2*m1];

C_Cor=Aa_In*Elastic*Bb;